import placeholder from '@/assets/images/card-placeholder.jpg'
import type { Rarity } from '@/constants/rarity'
import type { Card } from '@/types/card'

function card(
  id: number,
  name: string,
  rarity: Rarity,
  types: string[],
  set: string,
  theme: string,
  description: string,
  createdAt: string,
): Card {
  return {
    id,
    name,
    rarity,
    types,
    description,
    set,
    categories: [set, theme],
    createdAt,
    illustration: placeholder,
  }
}

